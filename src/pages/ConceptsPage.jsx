import React, { useState } from 'react'
import { useTranslation } from 'react-i18next'
import PropagationSection from '@/components/eeg/PropagationSection'

const SECTIONS = [
  {
    id: 'what',
    titleKey: 'concepts.what_is_eeg',
    content: `Electroencephalography (EEG) is a non-invasive neurophysiological technique that records the electrical activity of the brain through electrodes placed on the scalp. The signals reflect the summed postsynaptic potentials of millions of cortical neurons acting in synchrony — primarily pyramidal cells oriented perpendicular to the cortical surface.

EEG was first recorded in humans by Hans Berger in 1924. Today it remains a cornerstone of epilepsy diagnosis, sleep medicine, intraoperative monitoring, and critical care neurology due to its excellent temporal resolution (milliseconds) and relatively low cost.`,
  },
  {
    id: 'how',
    titleKey: 'concepts.how_it_works',
    content: `Scalp EEG electrodes detect very small voltage differences — typically 10–100 µV — generated by the underlying cortex. These signals pass through a differential amplifier which subtracts the signal at a reference electrode from the signal at the active electrode, cancelling common noise.

The amplified signal is filtered (typically 0.5–70 Hz bandpass + 50/60 Hz notch) and digitised at 256–512 Hz. Modern digital EEG allows retrospective montage reformatting, digital filtering, and quantitative analysis.`,
  },
  {
    id: 'placement',
    titleKey: 'concepts.electrode_placement',
    content: `The international 10-20 system standardises electrode placement using skull landmarks (nasion, inion, left and right preauricular points) as reference points. Electrodes are placed at 10% and 20% intervals along defined axes, ensuring consistent coverage of frontal, temporal, parietal, occipital, and central regions.

Standard clinical recordings use 19–21 electrodes. High-density EEG systems may use 64–256 channels for source localisation. Electrode names combine a letter (region) with a number: odd = left hemisphere, even = right hemisphere, 'z' = midline.`,
  },
  {
    id: '1020',
    titleKey: 'concepts.10_20_system',
    content: `Electrode regions and their prefixes:
• Fp — Frontopolar (prefrontal)
• F  — Frontal
• T  — Temporal
• C  — Central (over the motor/sensory cortex)
• P  — Parietal
• O  — Occipital
• A  — Auricular (ear reference)

The system ensures that regardless of head size, electrodes overlie consistent underlying cortical regions across patients and recording centres worldwide.`,
  },
  {
    id: 'propagation',
    titleKey: 'concepts.propagation',
    content: null,   // rendered by PropagationSection component
  },
]

export default function ConceptsPage() {
  const { t } = useTranslation()
  const [active, setActive] = useState('what')
  const section = SECTIONS.find(s => s.id === active)

  return (
    <div className="flex h-full overflow-hidden">

      {/* ── Section nav ─────────────────────────────────────────────────── */}
      <nav className="w-52 flex-shrink-0 border-r border-eeg-border p-4 overflow-y-auto">
        <p className="text-xs font-mono uppercase tracking-widest text-eeg-muted mb-3">Sections</p>
        <div className="space-y-1">
          {SECTIONS.map(s => (
            <button
              key={s.id}
              onClick={() => setActive(s.id)}
              className={`w-full text-left px-3 py-2.5 rounded-lg text-sm transition-all
                ${active === s.id
                  ? 'bg-eeg-accent bg-opacity-10 text-eeg-accent border border-eeg-accent border-opacity-20'
                  : 'text-eeg-muted hover:text-eeg-text hover:bg-eeg-border hover:bg-opacity-40'
                }`}
            >
              <span className="font-body">{t(s.titleKey)}</span>
              {s.id === 'propagation' && (
                <span className="ms-2 text-xs font-mono px-1.5 py-0.5 rounded"
                  style={{ color: '#FF6B35', background: '#FF6B3511', border: '1px solid #FF6B3533' }}>
                  Interactive
                </span>
              )}
            </button>
          ))}
        </div>
      </nav>

      {/* ── Content ─────────────────────────────────────────────────────── */}
      <div className="flex-1 overflow-y-auto px-10 py-10">
        <span className="label-tag mb-4 inline-block">{t('concepts.title')}</span>

        {/* Text sections */}
        {section && section.content !== null && (
          <>
            <h1 className="section-title mb-2">{t(section.titleKey)}</h1>
            <div className="mt-6 space-y-4 max-w-2xl">
              {section.content.split('\n\n').map((para, i) => (
                <p key={i} className="font-body text-eeg-muted leading-relaxed whitespace-pre-line text-sm">
                  {para}
                </p>
              ))}
            </div>
            {active === '1020' && <ElectrodeMap />}
          </>
        )}

        {/* Propagation interactive section */}
        {active === 'propagation' && (
          <PropagationSection />
        )}
      </div>
    </div>
  )
}

